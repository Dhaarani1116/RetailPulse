import os
from docx import Document
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from typing import List, Dict, Any

def export_worker_pdf(tasks: List[Dict[str, Any]], output_path: str) -> None:
    """
    Generate worker_tasks.pdf with task steps.
    """
    doc = SimpleDocTemplate(output_path, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'TitleStyle',
        parent=styles['Heading1'],
        textColor=colors.HexColor('#1A365D'),
        spaceAfter=12
    )
    normal_style = styles['Normal']
    
    cell_style = ParagraphStyle(
        'CellStyle',
        parent=styles['Normal'],
        fontSize=8,
        leading=10
    )
    
    story = []
    story.append(Paragraph("Floor Operations Task List", title_style))
    story.append(Paragraph("Instructions for floor workers on placement of accepted stock.", normal_style))
    story.append(Spacer(1, 15))
    
    # Table data
    table_data = [["SKU", "Action Required", "Destination Zone"]]
    for task in tasks:
        # Wrap action in a Paragraph for cell auto-wrapping
        action_text = task.get("action", "") or "Stock item to shelves"
        action_para = Paragraph(action_text, cell_style)
        
        table_data.append([
            task.get("sku", ""),
            action_para,
            task.get("zone", "")
        ])
        
    t = Table(table_data, colWidths=[120, 300, 120])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#2B6CB0')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('BACKGROUND', (0,1), (-1,-1), colors.HexColor('#F7FAFC')),
        ('GRID', (0,0), (-1,-1), 1, colors.HexColor('#E2E8F0')),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 8),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
    ]))
    
    story.append(t)
    doc.build(story)

def generate_po(items: List[Dict[str, Any]], output_path: str) -> None:
    """
    Generate purchase_order.docx containing purchase order details.
    """
    doc = Document()
    doc.add_heading("Purchase Order", level=1)
    
    doc.add_paragraph("Draft Purchase Order generated by RetailPulse automated intake system.")
    
    table = doc.add_table(rows=1, cols=3)
    hdr_cells = table.rows[0].cells
    hdr_cells[0].text = 'SKU'
    hdr_cells[1].text = 'Quantity'
    hdr_cells[2].text = 'Unit Price'
    
    for item in items:
        row_cells = table.add_row().cells
        row_cells[0].text = str(item.get("sku", ""))
        row_cells[1].text = str(item.get("quantity", 0))
        row_cells[2].text = f"${item.get('price', 0.0):.2f}"
        
    doc.save(output_path)

def parse_price_float(val: Any) -> float:
    if isinstance(val, (int, float)):
        return float(val)
    if not val:
        return 0.0
    try:
        # Clean currency symbols and commas
        clean_val = str(val).replace("$", "").replace("₹", "").replace(",", "").strip()
        return float(clean_val)
    except Exception:
        return 0.0

def draft_dispute_email(violations: List[Dict[str, Any]], output_path: str) -> None:
    """
    Draft a plain text email highlighting contract pricing violations.
    """
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write("Subject: Dispute: Pricing Mismatches Detected in Recent Delivery\n\n")
        f.write("Dear Supplier,\n\n")
        f.write("We have audited your recent shipment details and identified discrepancies between our agreed contract prices and your invoiced prices.\n\n")
        f.write("Discrepancies found:\n")
        for v in violations:
            expected = parse_price_float(v.get('expected_value', 0.0))
            actual = parse_price_float(v.get('actual_value', 0.0))
            diff = round(actual - expected, 2)
            f.write(f"- SKU {v.get('sku')}: Billed ${actual:.2f} instead of contract price ${expected:.2f}. (Difference: ${diff:.2f})\n")
        f.write("\nPlease adjust the invoice accordingly and send a revised version.\n\n")
        f.write("Sincerely,\nStore Purchasing Department\nRetailPulse Agent Workforce\n")

def generate_supplier_notice(supplier_name: str, reasoning: str, output_path: str) -> None:
    """
    Draft a rejection letter detailing delivery discrepancies.
    """
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(f"OFFICIAL SUPPLIER NOTICE OF SHIPMENT REJECTION\n")
        f.write(f"=============================================\n\n")
        f.write(f"Supplier: {supplier_name}\n")
        f.write(f"Date: 2026-07-28\n\n")
        f.write(f"Notice: Please be advised that the delivery received today has been rejected in part or whole for the following reasons:\n\n")
        f.write(reasoning + "\n\n")
        f.write("We request that you retrieve the items or dispatch a replacement matching store quality regulations immediately.\n\n")
        f.write("Thank you,\nRetailPulse Storage Operations Team\n")

def generate_manager_pdf(summary_data: Dict[str, Any], output_path: str) -> None:
    """
    Generate manager_summary.pdf with executive summary and key metrics.
    """
    doc = SimpleDocTemplate(output_path, pagesize=letter)
    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'TitleStyle',
        parent=styles['Heading1'],
        textColor=colors.HexColor('#1A365D'),
        spaceAfter=12
    )
    h2_style = ParagraphStyle(
        'Heading2Style',
        parent=styles['Heading2'],
        textColor=colors.HexColor('#2B6CB0'),
        spaceAfter=8
    )
    normal_style = styles['Normal']
    
    story = []
    story.append(Paragraph("Store Manager Intake Summary", title_style))
    story.append(Spacer(1, 10))
    
    # Dashboard metrics Table
    metrics_data = [
        ["Metric", "Value"],
        ["Accepted Items", str(summary_data.get("accepted_items_count", 0))],
        ["Rejected Items", str(summary_data.get("rejected_items_count", 0))],
        ["Pending Review", str(summary_data.get("pending_items_count", 0))],
        ["Total Accepted Value", f"${summary_data.get('total_value', 0.0):.2f}"],
        ["Supplier Score", f"{summary_data.get('supplier_score', 0.0):.1f} / 100"]
    ]
    
    t = Table(metrics_data, colWidths=[200, 200])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#1A365D')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
        ('BOTTOMPADDING', (0,0), (-1,0), 6),
        ('BACKGROUND', (0,1), (-1,-1), colors.HexColor('#F7FAFC')),
        ('GRID', (0,0), (-1,-1), 1, colors.HexColor('#E2E8F0')),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 10),
    ]))
    
    story.append(t)
    story.append(Spacer(1, 15))
    
    story.append(Paragraph("Executive Summary", h2_style))
    story.append(Paragraph(summary_data.get("executive_summary", ""), normal_style))
    
    doc.build(story)
